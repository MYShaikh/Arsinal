import { HttpClient, HttpErrorResponse } from '@angular/common/http';
import { Component, computed, inject, signal } from '@angular/core';
import { firstValueFrom } from 'rxjs';

import { API_BASE } from '../config';
import { AnimalCategory, WildlifeResult } from '../models';
import { MapService } from '../services/map.service';

const GROUPS: { category: AnimalCategory; title: string; blurb: string }[] = [
  { category: 'dangerous', title: 'Dangerous', blurb: 'Can injure by attacking, biting or crushing' },
  { category: 'venomous', title: 'Venomous', blurb: 'Inject venom by a bite or sting' },
  { category: 'poisonous', title: 'Poisonous', blurb: 'Harmful to touch or eat' },
];

/** Animals near you that can hurt a person, with a photo of each from Wikipedia. */
@Component({
  selector: 'app-wildlife',
  template: `
    <p class="note">Animals near {{ where() }} that can hurt you, with pictures from Wikipedia.</p>
    <button type="button" class="go" [disabled]="loading() || !maps.referencePoint()" (click)="load()">
      {{ loading() ? 'Looking up animals…' : result() ? 'Refresh for this spot' : 'Show dangerous animals here' }}
    </button>
    @if (loading()) {
      <p class="note">This usually takes 10 to 40 seconds.</p>
    }
    @if (error()) {
      <p class="note error" role="alert">{{ error() }}</p>
    }

    @if (result(); as r) {
      <p class="region">{{ r.region }}</p>
      @for (g of groups(); track g.category) {
        <h3>{{ g.title }} <span>{{ g.animals.length }}</span></h3>
        <p class="blurb">{{ g.blurb }}</p>
        @for (a of g.animals; track a.common_name) {
          <article>
            @if (a.image_url) {
              <img [src]="a.image_url" [alt]="a.common_name" loading="lazy" referrerpolicy="no-referrer" />
            } @else {
              <div class="noimg">No photo found</div>
            }
            <div class="body">
              <h4>{{ a.common_name }}</h4>
              <div class="latin">{{ a.scientific_name }}</div>
              <p><b>Risk:</b> {{ a.risk }}</p>
              <p><b>Stay safe:</b> {{ a.precaution }}</p>
              @if (a.page_url) {
                <a [href]="a.page_url" target="_blank" rel="noopener">Photo and more on Wikipedia</a>
              }
            </div>
          </article>
        }
      }
    }

    <p class="disclaimer">
      The list is generated by Gemini from your approximate area (about 50 km) and can be incomplete or wrong. It is
      not a substitute for local advice. In an emergency, call your local emergency number.
    </p>
  `,
  styles: `
    .note {
      margin: 12px 20px 0;
      color: var(--text-2);
      font-size: 13px;
      line-height: 1.45;
    }
    .note.error {
      color: #d93025;
    }
    .go {
      display: block;
      width: calc(100% - 32px);
      height: 42px;
      margin: 14px 16px 0;
      border: 0;
      border-radius: 21px;
      background: var(--primary);
      color: #fff;
      font: inherit;
      font-size: 15px;
      font-weight: 500;
      cursor: pointer;
    }
    .go:disabled {
      opacity: 0.7;
      cursor: progress;
    }
    .region {
      margin: 16px 20px 0;
      font-size: 16px;
      font-weight: 500;
    }
    h3 {
      display: flex;
      justify-content: space-between;
      margin: 18px 20px 0;
      font-size: 13px;
      font-weight: 500;
      text-transform: uppercase;
      letter-spacing: 0.6px;
    }
    h3 span {
      color: var(--text-2);
    }
    .blurb {
      margin: 2px 20px 0;
      color: var(--text-2);
      font-size: 12px;
    }
    article {
      margin: 10px 16px 0;
      overflow: hidden;
      border: 1px solid var(--border);
      border-radius: 12px;
      font-size: 14px;
      line-height: 1.45;
    }
    img,
    .noimg {
      display: block;
      width: 100%;
      height: 170px;
      object-fit: cover;
    }
    .noimg {
      display: flex;
      align-items: center;
      justify-content: center;
      background: var(--surface);
      color: var(--text-2);
      font-size: 13px;
    }
    .body {
      padding: 10px 14px 12px;
    }
    h4 {
      margin: 0;
      font-size: 16px;
      font-weight: 500;
    }
    .latin {
      color: var(--text-2);
      font-style: italic;
    }
    .body p {
      margin: 6px 0 0;
    }
    a {
      display: inline-block;
      margin-top: 8px;
      color: var(--primary);
      font-size: 13px;
    }
    .disclaimer {
      margin: 18px 20px 20px;
      padding-top: 12px;
      border-top: 1px solid var(--border);
      color: var(--text-2);
      font-size: 12px;
      line-height: 1.45;
    }
  `,
})
export class WildlifeComponent {
  private readonly http = inject(HttpClient);
  protected readonly maps = inject(MapService);

  protected readonly loading = signal(false);
  protected readonly error = signal('');
  protected readonly result = signal<WildlifeResult | null>(null);

  protected readonly groups = computed(() =>
    GROUPS.map((g) => ({ ...g, animals: this.result()?.animals.filter((a) => a.category === g.category) ?? [] })).filter(
      (g) => g.animals.length,
    ),
  );

  protected where() {
    const point = this.maps.referencePoint();
    return point?.source === 'you' ? 'your location' : 'the centre of the map';
  }

  protected async load() {
    const point = this.maps.referencePoint();
    if (!point) return;
    this.loading.set(true);
    this.error.set('');
    try {
      this.result.set(
        await firstValueFrom(
          this.http.get<WildlifeResult>(`${API_BASE}/wildlife/`, { params: { lat: point.lat, lng: point.lng } }),
        ),
      );
    } catch (e) {
      const detail = e instanceof HttpErrorResponse ? e.error?.detail : null;
      this.error.set(
        typeof detail === 'string'
          ? detail
          : "Couldn't reach the Arsenal backend to look up animals. Check that it is running.",
      );
    } finally {
      this.loading.set(false);
    }
  }
}
